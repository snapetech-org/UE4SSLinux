#!/usr/bin/env bash
set -euo pipefail

usage() {
  cat >&2 <<'EOF'
Usage:
  scripts/launch-proton-client-probe.sh [options] -- %command%
  scripts/launch-proton-client-probe.sh [options]

Options:
  --appid ID              Steam app id. Default: 1172710.
  --game-dir PATH         target profile install directory.
  --exe-rel PATH          Exe path relative to game dir.
                          Default: TargetGame/Binaries/Win64/TargetGame-Win64-Shipping.exe.
  --dll-name NAME.dll     Proxy DLL name staged for Wine override. Default: version.dll.
  --stage-dir PATH        Repo-contained staging directory.
  --stage-to-game-dir     Copy proxy DLL beside the game exe, with backup if needed.
  --unstage-game-dir      Remove the staged game-dir proxy only if it matches our DLL.

Recommended Steam launch option for target profile:
  /abs/path/scripts/launch-proton-client-probe.sh --stage-to-game-dir -- %command%

The default path stages the DLL outside the Steam game directory and sets
WINEDLLOVERRIDES, WINEPATH, and WINEDLLPATH for experiments. target profile's Proton path
should use --stage-to-game-dir so the proxy DLL is in the game DLL search path.
EOF
}

script_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
repo_root="$(cd "$script_dir/.." && pwd)"
appid="${UE4SSL_STEAM_APPID:-1172710}"
steam_root="${STEAM_ROOT:-$HOME/.steam/steam}"
game_dir="${UE4SSL_CLIENT_GAME_DIR:-}"
exe_rel="${UE4SSL_CLIENT_EXE_REL:-TargetGame/Binaries/Win64/TargetGame-Win64-Shipping.exe}"
dll_name="${UE4SSL_WIN_PROXY_DLL:-version.dll}"
sidecar_name="${UE4SSL_WIN_SIDECAR:-ue4ssl-win.env}"
build_dir="${UE4SSL_WINDOWS_LOADER_BUILD_DIR:-$repo_root/build/windows-client-loader}"
loader="${UE4SSL_WINDOWS_PRELOAD:-$build_dir/ue4ssl_windows_proxy_loader.dll}"
stage_dir="${UE4SSL_WIN_STAGE_DIR:-$build_dir/proton-stage}"
stage_to_game_dir=false
unstage_game_dir=false

while [ "$#" -gt 0 ]; do
  case "$1" in
    --appid)
      appid="${2:?missing value for --appid}"
      shift 2
      ;;
    --game-dir)
      game_dir="${2:?missing value for --game-dir}"
      shift 2
      ;;
    --exe-rel)
      exe_rel="${2:?missing value for --exe-rel}"
      shift 2
      ;;
    --dll-name)
      dll_name="${2:?missing value for --dll-name}"
      shift 2
      ;;
    --stage-dir)
      stage_dir="${2:?missing value for --stage-dir}"
      shift 2
      ;;
    --stage-to-game-dir)
      stage_to_game_dir=true
      shift
      ;;
    --unstage-game-dir)
      unstage_game_dir=true
      shift
      ;;
    --help|-h)
      usage
      exit 0
      ;;
    --)
      shift
      break
      ;;
    *)
      break
      ;;
  esac
done

if [[ "$dll_name" != *.dll ]]; then
  dll_name="${dll_name}.dll"
fi
override_name="${dll_name%.dll}"

acf="$steam_root/steamapps/appmanifest_${appid}.acf"
if [ -z "$game_dir" ] && [ -f "$acf" ]; then
  install_dir="$(awk -F '"' '/"installdir"/ {print $4; exit}' "$acf")"
  if [ -n "$install_dir" ]; then
    game_dir="$steam_root/steamapps/common/$install_dir"
  fi
fi

if [ ! -f "$loader" ]; then
  "$repo_root/scripts/build-windows-client-loader.sh" >/dev/null
fi

if [ ! -r "$loader" ]; then
  echo "Windows client probe DLL is not readable: $loader" >&2
  exit 1
fi

posix_to_win_path() {
  local path="$1"
  if command -v winepath >/dev/null 2>&1; then
    WINEDEBUG=-all winepath -w "$path" 2>/dev/null && return 0
  fi
  printf 'Z:%s\n' "${path//\//\\}"
}

same_file_content() {
  local a="$1"
  local b="$2"
  [ -f "$a" ] && [ -f "$b" ] && cmp -s "$a" "$b"
}

manifest_owned_target() {
  local target="$1"
  local manifest_file="$2"
  [ -f "$target" ] || return 1
  [ -f "$manifest_file" ] || return 1
  local manifest_target
  manifest_target="$(awk -F '=' '/^target=/ {print $2; exit}' "$manifest_file")"
  [ "$manifest_target" = "$target" ] || return 1
  local manifest_sha
  manifest_sha="$(awk '/  / {print $1; exit}' "$manifest_file")"
  [ -n "$manifest_sha" ] || return 1
  local current_sha
  current_sha="$(sha256sum "$target" | awk '{print $1}')"
  [ "$manifest_sha" = "$current_sha" ]
}

manifest_owned_sidecar() {
  local sidecar="$1"
  local manifest_file="$2"
  [ -f "$sidecar" ] || return 1
  [ -f "$manifest_file" ] || return 1
  local manifest_sidecar
  manifest_sidecar="$(awk -F '=' '/^sidecar=/ {print $2; exit}' "$manifest_file")"
  [ "$manifest_sidecar" = "$sidecar" ] || return 1
  local manifest_sha
  manifest_sha="$(awk -v path="$sidecar" '$2 == path {print $1; exit}' "$manifest_file")"
  [ -n "$manifest_sha" ] || return 1
  local current_sha
  current_sha="$(sha256sum "$sidecar" | awk '{print $1}')"
  [ "$manifest_sha" = "$current_sha" ]
}

write_sidecar_config() {
  local path="$1"
  cat > "$path" <<EOF
# Generated by launch-proton-client-probe.sh. Environment variables override these values.
UE4SSL_WIN_LOG=$UE4SSL_WIN_LOG
UE4SSL_WIN_SNAPSHOT_DELAY_SECONDS=$UE4SSL_WIN_SNAPSHOT_DELAY_SECONDS
UE4SSL_WIN_LOG_MODULES=$UE4SSL_WIN_LOG_MODULES
UE4SSL_WIN_SCAN_ENABLED=$UE4SSL_WIN_SCAN_ENABLED
UE4SSL_WIN_SCAN_PRESETS=$UE4SSL_WIN_SCAN_PRESETS
UE4SSL_WIN_SCAN_STRINGS=${UE4SSL_WIN_SCAN_STRINGS:-}
UE4SSL_WIN_SCAN_SIGNATURES=${UE4SSL_WIN_SCAN_SIGNATURES:-}
UE4SSL_WIN_SCAN_SIGNATURES_FILE=${UE4SSL_WIN_SCAN_SIGNATURES_FILE:-}
UE4SSL_WIN_UE_ANCHORS=${UE4SSL_WIN_UE_ANCHORS:-}
UE4SSL_WIN_UE_ANCHOR_SIGNATURES=${UE4SSL_WIN_UE_ANCHOR_SIGNATURES:-}
UE4SSL_WIN_UE_ANCHOR_SIGNATURES_FILE=${UE4SSL_WIN_UE_ANCHOR_SIGNATURES_FILE:-}
UE4SSL_WIN_UE_POINTER_PROBE=${UE4SSL_WIN_UE_POINTER_PROBE:-false}
UE4SSL_WIN_UE_LAYOUT_PROBE=${UE4SSL_WIN_UE_LAYOUT_PROBE:-false}
UE4SSL_WIN_UE_UOBJECT_PROBE=${UE4SSL_WIN_UE_UOBJECT_PROBE:-false}
UE4SSL_WIN_UE_LAYOUT_SLOTS=${UE4SSL_WIN_UE_LAYOUT_SLOTS:-8}
UE4SSL_WIN_HOOK_SELF_TEST=${UE4SSL_WIN_HOOK_SELF_TEST:-false}
UE4SSL_WIN_MOD_SELF_TEST=${UE4SSL_WIN_MOD_SELF_TEST:-false}
UE4SSL_WIN_LUA_SELF_TEST=${UE4SSL_WIN_LUA_SELF_TEST:-false}
UE4SSL_WIN_LUA_DLL=${UE4SSL_WIN_LUA_DLL:-}
UE4SSL_WIN_LUA_SELF_TEST_SCRIPT=${UE4SSL_WIN_LUA_SELF_TEST_SCRIPT:-}
UE4SSL_WIN_LUA_REFLECTION_SELF_TEST=${UE4SSL_WIN_LUA_REFLECTION_SELF_TEST:-false}
UE4SSL_WIN_LUA_REFLECTION_SELF_TEST_SCRIPT=${UE4SSL_WIN_LUA_REFLECTION_SELF_TEST_SCRIPT:-}
UE4SSL_WIN_UE_PROCESS_EVENT_HOOK_PROBE=${UE4SSL_WIN_UE_PROCESS_EVENT_HOOK_PROBE:-false}
UE4SSL_WIN_UE_PROCESS_EVENT_HOOK_ADDRESS=${UE4SSL_WIN_UE_PROCESS_EVENT_HOOK_ADDRESS:-}
UE4SSL_WIN_UE_PROCESS_EVENT_ADDRESS=${UE4SSL_WIN_UE_PROCESS_EVENT_ADDRESS:-}
UE4SSL_WIN_UE_PROCESS_EVENT_HOOK_SELF_TEST_TARGET=${UE4SSL_WIN_UE_PROCESS_EVENT_HOOK_SELF_TEST_TARGET:-false}
UE4SSL_WIN_UE_PROCESS_EVENT_HOOK_INSTALL=${UE4SSL_WIN_UE_PROCESS_EVENT_HOOK_INSTALL:-false}
UE4SSL_WIN_UE_PROCESS_EVENT_HOOK_CALL_SELF_TEST=${UE4SSL_WIN_UE_PROCESS_EVENT_HOOK_CALL_SELF_TEST:-false}
UE4SSL_WIN_UE_PROCESS_EVENT_LIVE_HOOK=${UE4SSL_WIN_UE_PROCESS_EVENT_LIVE_HOOK:-false}
UE4SSL_WIN_UE_PROCESS_EVENT_LIVE_HOOK_ADDRESS=${UE4SSL_WIN_UE_PROCESS_EVENT_LIVE_HOOK_ADDRESS:-}
UE4SSL_WIN_UE_PROCESS_EVENT_LIVE_HOOK_SELF_TEST_TARGET=${UE4SSL_WIN_UE_PROCESS_EVENT_LIVE_HOOK_SELF_TEST_TARGET:-false}
UE4SSL_WIN_UE_PROCESS_EVENT_LIVE_HOOK_CALL_SELF_TEST=${UE4SSL_WIN_UE_PROCESS_EVENT_LIVE_HOOK_CALL_SELF_TEST:-false}
UE4SSL_WIN_UE_PROCESS_EVENT_LIVE_HOOK_LOG_CALLS=${UE4SSL_WIN_UE_PROCESS_EVENT_LIVE_HOOK_LOG_CALLS:-false}
UE4SSL_WIN_UE_PROCESS_EVENT_LIVE_HOOK_CALL_LOG_LIMIT=${UE4SSL_WIN_UE_PROCESS_EVENT_LIVE_HOOK_CALL_LOG_LIMIT:-8}
UE4SSL_WIN_UE_PROCESS_EVENT_DISPATCH_SELF_TEST=${UE4SSL_WIN_UE_PROCESS_EVENT_DISPATCH_SELF_TEST:-false}
UE4SSL_WIN_UE_PROCESS_EVENT_LIVE_LUA_DISPATCH=${UE4SSL_WIN_UE_PROCESS_EVENT_LIVE_LUA_DISPATCH:-false}
UE4SSL_WIN_UE_PROCESS_EVENT_LIVE_LUA_SCRIPT=${UE4SSL_WIN_UE_PROCESS_EVENT_LIVE_LUA_SCRIPT:-}
UE4SSL_WIN_LUA_PROCESS_EVENT_SELF_TEST=${UE4SSL_WIN_LUA_PROCESS_EVENT_SELF_TEST:-false}
UE4SSL_WIN_LUA_PROCESS_EVENT_SELF_TEST_SCRIPT=${UE4SSL_WIN_LUA_PROCESS_EVENT_SELF_TEST_SCRIPT:-}
UE4SSL_WIN_LUA_MODS_ENABLED=${UE4SSL_WIN_LUA_MODS_ENABLED:-false}
UE4SSL_WIN_LUA_MOD_SCRIPTS=${UE4SSL_WIN_LUA_MOD_SCRIPTS:-}
UE4SSL_WIN_LUA_MOD_ROOT=${UE4SSL_WIN_LUA_MOD_ROOT:-}
UE4SSL_WIN_LUA_MOD_DISPATCH_SELF_TEST=${UE4SSL_WIN_LUA_MOD_DISPATCH_SELF_TEST:-false}
UE4SSL_WIN_SCAN_MAX_HITS_PER_NEEDLE=$UE4SSL_WIN_SCAN_MAX_HITS_PER_NEEDLE
UE4SSL_WIN_SCAN_MAX_REGION_BYTES=$UE4SSL_WIN_SCAN_MAX_REGION_BYTES
UE4SSL_WIN_SCAN_PRIVATE=${UE4SSL_WIN_SCAN_PRIVATE:-false}
UE4SSL_WIN_AUTO_THREAD=${UE4SSL_WIN_AUTO_THREAD:-true}
EOF
  chmod 0644 "$path"
}

stage_overlay="$stage_dir/$dll_name"
mkdir -p "$stage_dir"
cp "$loader" "$stage_overlay"
chmod 0644 "$stage_overlay"

manifest="$build_dir/game-dir-stage-manifest.txt"
game_exe=""
game_exe_dir=""
if [ -n "$game_dir" ]; then
  game_exe="$game_dir/$exe_rel"
  game_exe_dir="$(dirname "$game_exe")"
fi

if $unstage_game_dir; then
  if [ -z "$game_exe_dir" ]; then
    echo "--unstage-game-dir needs --game-dir or a readable Steam appmanifest" >&2
    exit 2
  fi
  target="$game_exe_dir/$dll_name"
  if same_file_content "$target" "$loader"; then
    rm -f "$target"
    printf 'removed staged proxy DLL: %s\n' "$target"
    sidecar="$(awk -F '=' '/^sidecar=/ {print $2; exit}' "$manifest" 2>/dev/null || true)"
    if [ -n "$sidecar" ] && manifest_owned_sidecar "$sidecar" "$manifest"; then
      rm -f "$sidecar"
      printf 'removed staged sidecar config: %s\n' "$sidecar"
    fi
    rm -f "$manifest"
  else
    printf 'not removing %s: missing or content differs from current loader\n' "$target" >&2
    exit 1
  fi
  exit 0
fi

active_stage_dir="$stage_dir"
if $stage_to_game_dir; then
  if [ -z "$game_exe_dir" ] || [ ! -d "$game_exe_dir" ]; then
    echo "--stage-to-game-dir needs a valid game exe directory; got: ${game_exe_dir:-<unknown>}" >&2
    exit 2
  fi
  target="$game_exe_dir/$dll_name"
  mkdir -p "$build_dir"
  if [ -e "$target" ] &&
     ! same_file_content "$target" "$loader" &&
     ! manifest_owned_target "$target" "$manifest"; then
    backup="$target.ue4ssl-backup.$(date -u +%Y%m%dT%H%M%SZ)"
    cp -a "$target" "$backup"
    printf 'backed up existing %s to %s\n' "$target" "$backup" >&2
  fi
  cp "$loader" "$target"
  chmod 0644 "$target"
  {
    printf 'time=%s\n' "$(date -u +%Y-%m-%dT%H:%M:%SZ)"
    printf 'target=%s\n' "$target"
    printf 'source=%s\n' "$loader"
    sha256sum "$target"
  } > "$manifest"
  active_stage_dir="$game_exe_dir"
fi

stage_win="$(posix_to_win_path "$active_stage_dir")"
default_log_posix="${UE4SSL_WIN_LOG_POSIX:-/tmp/ue4ssl-win-client-probe-loader.log}"
default_log_win="$(posix_to_win_path "$default_log_posix")"

if [ -z "${UE4SSL_WIN_LOG+x}" ]; then
  export UE4SSL_WIN_LOG="$default_log_win"
fi
if [ -z "${UE4SSL_WIN_SCAN_ENABLED+x}" ]; then
  export UE4SSL_WIN_SCAN_ENABLED=true
fi
if [ -z "${UE4SSL_WIN_LOG_MODULES+x}" ]; then
  export UE4SSL_WIN_LOG_MODULES=true
fi
if [ -z "${UE4SSL_WIN_SCAN_PRESETS+x}" ]; then
  export UE4SSL_WIN_SCAN_PRESETS=core,ue,client,cheat,brt,deep-desert
fi
if [ -z "${UE4SSL_WIN_SCAN_MAX_HITS_PER_NEEDLE+x}" ]; then
  export UE4SSL_WIN_SCAN_MAX_HITS_PER_NEEDLE=16
fi
if [ -z "${UE4SSL_WIN_SCAN_MAX_REGION_BYTES+x}" ]; then
  export UE4SSL_WIN_SCAN_MAX_REGION_BYTES=268435456
fi
if [ -z "${UE4SSL_WIN_SNAPSHOT_DELAY_SECONDS+x}" ]; then
  export UE4SSL_WIN_SNAPSHOT_DELAY_SECONDS=2
fi

sidecar_path="$active_stage_dir/$sidecar_name"
if $stage_to_game_dir && [ -e "$sidecar_path" ] && ! manifest_owned_sidecar "$sidecar_path" "$manifest"; then
  sidecar_backup="$sidecar_path.ue4ssl-backup.$(date -u +%Y%m%dT%H%M%SZ)"
  cp -a "$sidecar_path" "$sidecar_backup"
  printf 'backed up existing %s to %s\n' "$sidecar_path" "$sidecar_backup" >&2
fi
write_sidecar_config "$sidecar_path"

if $stage_to_game_dir; then
  {
    printf 'time=%s\n' "$(date -u +%Y-%m-%dT%H:%M:%SZ)"
    printf 'target=%s\n' "$target"
    printf 'sidecar=%s\n' "$sidecar_path"
    printf 'source=%s\n' "$loader"
    sha256sum "$target"
    sha256sum "$sidecar_path"
  } > "$manifest"
fi

if [ -n "${WINEDLLOVERRIDES:-}" ]; then
  export WINEDLLOVERRIDES="${override_name}=n,b;${WINEDLLOVERRIDES}"
else
  export WINEDLLOVERRIDES="${override_name}=n,b"
fi

if [ -n "${WINEPATH:-}" ]; then
  export WINEPATH="${stage_win};${WINEPATH}"
else
  export WINEPATH="$stage_win"
fi

if [ -n "${WINEDLLPATH:-}" ]; then
  export WINEDLLPATH="${active_stage_dir}:${WINEDLLPATH}"
else
  export WINEDLLPATH="$active_stage_dir"
fi

if [ "$#" -eq 0 ]; then
  cat <<EOF
Windows client probe staged.

proxy_dll=$stage_overlay
active_stage_dir=$active_stage_dir
sidecar_config=$sidecar_path
dll_override=$WINEDLLOVERRIDES
winepath=$WINEPATH
winedllpath=$WINEDLLPATH
probe_log=$UE4SSL_WIN_LOG

Recommended Steam launch option for target profile:
$repo_root/scripts/launch-proton-client-probe.sh --stage-to-game-dir -- %command%

Non-mutating overlay experiment:
$repo_root/scripts/launch-proton-client-probe.sh -- %command%

Direct command shape:
WINEDLLOVERRIDES='$WINEDLLOVERRIDES' WINEPATH='$WINEPATH' WINEDLLPATH='$WINEDLLPATH' UE4SSL_WIN_LOG='$UE4SSL_WIN_LOG' <proton-or-wine-command>
EOF
  exit 0
fi

exec "$@"
